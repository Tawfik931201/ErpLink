import type { OdooClient } from '@/lib/odoo-client'

type Field = { type: string; relation?: string; selection?: Array<[string, string]> }
type Schema = Record<string, Field>
const schemas = new WeakMap<OdooClient, Map<string, Promise<Schema>>>()

async function fields(client: OdooClient, model: string): Promise<Schema> {
  let cache = schemas.get(client)
  if (!cache) { cache = new Map(); schemas.set(client, cache) }
  const saved = cache.get(model)
  if (saved) return saved
  const read = client.execute<Schema>(model, 'fields_get', [], { attributes: ['type', 'relation', 'selection'] })
    .then(schema => {
      if (!schema || typeof schema !== 'object' || !Object.keys(schema).length || Array.isArray(schema)) throw new Error(`Cannot validate Odoo ${model} fields`)
      return schema
    }).catch(error => { cache!.delete(model); throw error })
  cache.set(model, read)
  return read
}

/** Validate the assembled payload, including related IDs, before creating the SO. */
export async function validateOrderPayload(
  client: OdooClient,
  values: Record<string, unknown>,
  options: { create: boolean; pendingCustomer?: Record<string, unknown>; explicitFields?: string[] },
): Promise<void> {
  const orderSchema = await fields(client, 'sale.order')
  if (options.create && !values.company_id) {
    const defaults = await client.execute<Record<string, unknown>>('sale.order', 'default_get', [['company_id']])
    if (!Number.isSafeInteger(defaults?.company_id) || Number(defaults.company_id) <= 0) throw new Error('Order company could not be resolved before writing')
    values.company_id = defaults.company_id
  }
  const references = new Map<string, Set<number>>()
  const remember = (model: string, id: unknown) => {
    if (typeof id !== 'number' || !Number.isSafeInteger(id) || id <= 0) throw new Error(`Invalid related Odoo ID for ${model}`)
    let ids = references.get(model)
    if (!ids) { ids = new Set(); references.set(model, ids) }
    ids.add(id)
  }
  const check = (model: string, data: Record<string, unknown>, schema: Schema) => {
    for (const [key, value] of Object.entries(data)) {
      const meta = schema[key]
      if (!meta) throw new Error(`Configured order field ${model}.${key} does not exist`)
      if (value === false || value === null || value === undefined) continue
      if (meta.type === 'many2one' && meta.relation) remember(meta.relation, value)
      if (['integer', 'float', 'monetary'].includes(meta.type) && (typeof value !== 'number' || !Number.isFinite(value))) {
        throw new Error(`Invalid order number ${model}.${key}`)
      }
      if (meta.type === 'selection' && meta.selection?.length && !meta.selection.some(([option]) => option === value)) {
        throw new Error(`Invalid configured order selection ${model}.${key}`)
      }
      if (meta.type === 'many2many' && meta.relation) {
        if (!Array.isArray(value)) throw new Error(`Invalid relation commands ${model}.${key}`)
        for (const command of value) {
          if (!Array.isArray(command)) throw new Error(`Invalid relation command ${model}.${key}`)
          if (command[0] === 6 && Array.isArray(command[2])) command[2].forEach(id => remember(meta.relation!, id))
          else if (command[0] === 4) remember(meta.relation, command[1])
          else if (command[0] !== 5) throw new Error(`Unsupported relation command ${model}.${key}`)
        }
      }
    }
  }
  // These optional decorations are generated by the engine, never required
  // configuration. Remove them before the first write if this database lacks them.
  const explicit = new Set(options.explicitFields || [])
  for (const key of ['x_coupon_code', 'journal_id', 'x_payment_method_id']) {
    if (!orderSchema[key] && !explicit.has(key)) delete values[key]
  }
  check('sale.order', values, orderSchema)
  if (options.pendingCustomer) {
    if (!String(options.pendingCustomer.name || '').trim()) throw new Error('Order customer name is missing')
    if (values.company_id && options.pendingCustomer.company_id && options.pendingCustomer.company_id !== values.company_id) throw new Error('Configured customer belongs to another Odoo company')
    check('res.partner', options.pendingCustomer, await fields(client, 'res.partner'))
  }
  if (options.create) {
    if (!values.partner_id && !options.pendingCustomer) throw new Error('Order customer is not resolved')
    if (!Array.isArray(values.order_line) || !values.order_line.length) throw new Error('Order has no prepared line items')
  }
  if (Array.isArray(values.order_line)) {
    const lineSchema = await fields(client, 'sale.order.line')
    for (const command of values.order_line) {
      if (!Array.isArray(command) || command[0] !== 0 || !command[2] || typeof command[2] !== 'object') throw new Error('Order line is not fully prepared')
      const line = command[2] as Record<string, unknown>
      if (!line.product_id) throw new Error('Order line product is not resolved')
      if (typeof line.product_uom_qty !== 'number' || !Number.isFinite(line.product_uom_qty) || line.product_uom_qty < 0) throw new Error('Order line quantity is invalid')
      if (typeof line.price_unit !== 'number' || !Number.isFinite(line.price_unit)) throw new Error('Order line price is invalid')
      check('sale.order.line', line, lineSchema)
      if (line.analytic_distribution && typeof line.analytic_distribution === 'object') {
        for (const [accounts, percentage] of Object.entries(line.analytic_distribution)) {
          if (typeof percentage !== 'number' || !Number.isFinite(percentage) || percentage < 0) throw new Error('Order analytic percentage is invalid')
          accounts.split(',').forEach(id => remember('account.analytic.account', Number(id)))
        }
      }
    }
  }
  // One read per referenced model, not one request per line or field.
  const companyModels = new Set(['res.partner', 'product.product', 'account.tax', 'account.analytic.account', 'account.account', 'stock.warehouse', 'product.pricelist', 'account.payment.term', 'account.fiscal.position'])
  const orderCompany = Number(values.company_id || 0)
  for (const [model, ids] of references) {
    const modelSchema = companyModels.has(model) ? await fields(client, model) : null
    const hasSingleCompany = !!modelSchema?.company_id
    const hasMultipleCompanies = model === 'account.account' && !!modelSchema?.company_ids
    const readFields = ['id', ...(hasSingleCompany ? ['company_id'] : []), ...(hasMultipleCompanies ? ['company_ids'] : [])]
    const rows = await client.searchRead<{ id: number; company_id?: number | [number, string] | false; company_ids?: number[] }>(model, [['id', 'in', [...ids]]], readFields, ids.size)
    const found = new Set(rows.map(row => row.id))
    if ([...ids].some(id => !found.has(id))) throw new Error(`Configured order references a missing or inaccessible ${model} record`)
    if (orderCompany && rows.some(row => {
      const companyId = Array.isArray(row.company_id) ? row.company_id[0] : row.company_id
      if (hasMultipleCompanies && Array.isArray(row.company_ids) && row.company_ids.length) {
        return !row.company_ids.includes(orderCompany)
      }
      return hasSingleCompany && companyId && companyId !== orderCompany
    })) throw new Error(`Configured order ${model} belongs to another Odoo company`)
  }
}
