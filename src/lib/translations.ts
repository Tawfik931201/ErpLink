/**
 * Automatically cleans up mixed language labels dynamically based on the current language.
 * E.g., "Name (الاسم)" => "Name" in English, "الاسم" in Arabic.
 * "فارغ (Clear)" => "Clear" in English, "فارغ" in Arabic.
 */
export function formatFieldLabel(label: string, lang: 'ar' | 'en'): string {
  if (!label) return '';
  const hasArabic = (str: string) => /[\u0600-\u06FF]/.test(str);
  if (!hasArabic(label)) {
    return label; // Keep technical IDs and purely English terms intact
  }
  const match = label.match(/^([^(]+)\(([^)]+)\)$/);
  if (match) {
    const part1 = match[1].trim();
    const part2 = match[2].trim();
    if (hasArabic(part1)) {
      return lang === 'ar' ? part1 : part2;
    } else {
      return lang === 'ar' ? part2 : part1;
    }
  }
  return label;
}
