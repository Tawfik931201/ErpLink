import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(path, 'utf8')
const card = JSON.parse(read('public/.well-known/mcp/server-card.json'))
const catalog = JSON.parse(read('public/.well-known/ai-catalog.json'))
const browser = read('public/agent-tools.js')
const middleware = read('src/middleware.ts')
const mcp = read('src/lib/public-mcp.ts')
const markdown = read('src/app/api/public-markdown/route.ts')
const business = read('src/lib/public-business-profile.ts')

assert.equal(card.$schema, 'https://static.modelcontextprotocol.io/schemas/v1/server-card.schema.json')
assert.equal(card.name, 'com.bizsahla.erplink/public')
assert.equal(card.version, '1.0.0')
assert.equal(card.remotes[0].type, 'streamable-http')
assert.equal(card.remotes[0].url, 'https://erplink.bizsahla.com/api/public-mcp')
assert.deepEqual(card.remotes[0].supportedProtocolVersions, ['2025-06-18'])
assert.equal(catalog.entries[0].url, 'https://erplink.bizsahla.com/.well-known/mcp/server-card.json')
assert.ok(read('src/app/api/public-mcp/route.ts').includes('handlePublicMcp(input)'))
assert.ok(mcp.includes("name: 'read_public_page'"))
assert.ok(mcp.includes('isAgentPublicPath(path)'))
assert.ok(middleware.includes('isAgentPublicPath(publicPath)'))
assert.ok(middleware.includes("type === 'text/markdown'"))
assert.ok(markdown.includes("'Content-Type': 'text/markdown; charset=utf-8'"))
assert.ok(browser.includes('document.modelContext.registerTool'))
assert.ok(browser.includes('readOnlyHint: true'))
assert.ok(!browser.includes('navigator.modelContext'))
assert.ok(!browser.includes('/api/'))
assert.ok(business.includes('PUBLIC_BUSINESS_PHONE_E164'))
assert.ok(business.includes('PUBLIC_BUSINESS_SAME_AS'))
console.log('Agent readiness verification passed: static discovery, real MCP handler, safe Markdown, WebMCP and verified-only business fields.')
