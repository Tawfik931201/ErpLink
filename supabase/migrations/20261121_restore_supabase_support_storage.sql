-- ERP Link administrative support tickets: Supabase is the source of truth.
-- Applied to ecommerce Supabase on 2026-11-21.
CREATE TABLE IF NOT EXISTS public.support_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id),
  user_id text NOT NULL,
  email text NOT NULL,
  contact_name text,
  subject text NOT NULL,
  description text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  source_ref text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS support_tickets_scope_idx
  ON public.support_tickets(workspace_id, user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.support_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
  author_id text,
  author_name text NOT NULL DEFAULT '',
  body text NOT NULL,
  source_ref text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS support_messages_ticket_time_idx
  ON public.support_messages(ticket_id, created_at, id);

ALTER TABLE public.support_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_messages ENABLE ROW LEVEL SECURITY;
-- All ticket access goes through authenticated Clerk server actions using a
-- private service-role connection after verifying workspace and ownership.
REVOKE ALL ON TABLE public.support_tickets, public.support_messages
  FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.support_tickets_id_seq,
  public.support_messages_id_seq FROM anon, authenticated;
